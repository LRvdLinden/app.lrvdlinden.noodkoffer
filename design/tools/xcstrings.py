def catalog(strings):
    out = {"sourceLanguage": "en", "strings": {}, "version": "1.0"}
    for key in sorted(strings):
        out["strings"][key] = {"localizations": {"nl": {"stringUnit": {"state": "translated", "value": strings[key]}}}}
    return out

