def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s.startswith("@") or s.startswith("?"): s = "\\" + s
    return s

for lang, idx, folder in (("en", 0, "values"), ("nl", 1, "values-nl")):
    os.makedirs(f"{R}/res/{folder}", exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for k, v in S.items():
        attr = ' translatable="false"' if k == "app_name" and lang == "en" else ""
        if k == "app_name" and lang == "nl": continue
        lines.append(f'    <string name="{k}"{attr}>{esc(v[idx])}</string>')
    for k, v in ARRAYS.items():
        lines.append(f'    <string-array name="{k}">')
        for item in v[idx]: lines.append(f'        <item>{esc(item)}</item>')
        lines.append('    </string-array>')
    lines.append("</resources>")
    open(f"{R}/res/{folder}/strings.xml", "w").write("\n".join(lines) + "\n")

